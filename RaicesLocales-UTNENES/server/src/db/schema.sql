-- Esquema inicial de Raíces Locales.
-- Crear primero la base de datos desde pgAdmin y ejecutar este archivo
-- con el Query Tool conectado a esa base.

BEGIN;

CREATE TABLE IF NOT EXISTS public.artesanos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL CHECK (btrim(nombre) <> ''),
  foto_perfil TEXT,
  categoria VARCHAR(80) NOT NULL CHECK (btrim(categoria) <> ''),
  ubicacion VARCHAR(160),
  historia TEXT,
  suscripcion VARCHAR(40) NOT NULL DEFAULT 'Básica'
);

CREATE TABLE IF NOT EXISTS public.productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(160) NOT NULL CHECK (btrim(nombre) <> ''),
  descripcion TEXT NOT NULL DEFAULT '',
  precio NUMERIC(12, 2) NOT NULL CHECK (precio >= 0),
  stock INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
  categoria VARCHAR(80) NOT NULL CHECK (btrim(categoria) <> ''),
  imagen TEXT,
  destacado BOOLEAN NOT NULL DEFAULT FALSE,
  artesano_id BIGINT NOT NULL
    REFERENCES public.artesanos (id)
    ON UPDATE CASCADE
    ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS productos_artesano_id_idx
  ON public.productos (artesano_id);

CREATE INDEX IF NOT EXISTS productos_categoria_idx
  ON public.productos (categoria);

CREATE INDEX IF NOT EXISTS productos_destacados_nombre_idx
  ON public.productos (nombre)
  WHERE destacado IS TRUE;

CREATE TABLE IF NOT EXISTS public.usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL CHECK (btrim(nombre) <> ''),
  apellido VARCHAR(80) NOT NULL CHECK (btrim(apellido) <> ''),
  email VARCHAR(254) NOT NULL,
  password_hash CHAR(128) NOT NULL,
  password_salt CHAR(32) NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS usuarios_email_lower_idx
  ON public.usuarios (LOWER(email));

CREATE TABLE IF NOT EXISTS public.sesiones (
  token_hash CHAR(64) PRIMARY KEY,
  usuario_id BIGINT NOT NULL
    REFERENCES public.usuarios (id)
    ON DELETE CASCADE,
  vence_en TIMESTAMPTZ NOT NULL,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS sesiones_vence_en_idx
  ON public.sesiones (vence_en);

CREATE TABLE IF NOT EXISTS public.pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  numero VARCHAR(32) NOT NULL UNIQUE,
  usuario_id BIGINT NOT NULL
    REFERENCES public.usuarios (id)
    ON DELETE RESTRICT,
  comprador_nombre VARCHAR(80) NOT NULL,
  comprador_apellido VARCHAR(80) NOT NULL,
  comprador_email VARCHAR(254) NOT NULL,
  comprador_telefono VARCHAR(40) NOT NULL,
  envio_tipo VARCHAR(20) NOT NULL CHECK (envio_tipo IN ('retiro', 'domicilio')),
  envio_costo NUMERIC(12, 2) NOT NULL CHECK (envio_costo >= 0),
  envio_direccion TEXT,
  subtotal NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0),
  total NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
  estado VARCHAR(20) NOT NULL DEFAULT 'iniciado'
    CHECK (estado IN ('iniciado', 'aprobado', 'pendiente', 'rechazado')),
  pago JSONB,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS pedidos_usuario_creado_idx
  ON public.pedidos (usuario_id, creado_en DESC);

CREATE TABLE IF NOT EXISTS public.pedido_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL
    REFERENCES public.pedidos (id)
    ON DELETE CASCADE,
  producto_id BIGINT
    REFERENCES public.productos (id)
    ON DELETE SET NULL,
  producto_nombre VARCHAR(160) NOT NULL,
  producto_imagen TEXT,
  producto_categoria VARCHAR(80) NOT NULL,
  precio_unitario NUMERIC(12, 2) NOT NULL CHECK (precio_unitario >= 0),
  cantidad INTEGER NOT NULL CHECK (cantidad > 0),
  UNIQUE (pedido_id, producto_id)
);

CREATE INDEX IF NOT EXISTS pedido_items_pedido_id_idx
  ON public.pedido_items (pedido_id);

COMMIT;
